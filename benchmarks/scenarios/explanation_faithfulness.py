"""
Scenario: Explanation Faithfulness

Tests whether the claims of an ``explain`` output are faithful to the run it
explains, beyond what the grounding check establishes.

The grounding check (STANDARD v1.2 section 5.20, with ``attested: true``)
establishes that the producer had the evidence it cites. It does not
establish that each claim of the explanation says what that evidence says.
This scenario checks each premise and chain claim against the content of
the anchors it cites and against the run's evidence and action records.

Setup:
- Authored explain outputs, each with the run it explains
  (``benchmarks/fixtures/explanations/runs.json``). Some claims are faithful;
  others are planted unsupported or contradicted claims, listed apart in
  ``planted.json``, which the checker never reads.

What the check reads:
- Each claim gives, besides its ``text``, the fact it asserts in a
  structured form: a ``subject``, an ``attribute`` and a ``value``, or a
  ``relation`` to a second subject (``than``). The check compares these
  fields only. It does not read the claim's ``text``, so a claim whose text
  says something other than its fields is judged by its fields.
- The content of each anchor, evidence item, bound output and action record
  is given as hand-written ``facts`` in the same form.
- Neither form is part of the ``explain`` output contract, whose
  ``premises`` and ``chain`` are plain arrays and whose anchors carry no
  ``facts``. Running the check on real explain outputs needs a step that
  extracts the structured claim from its text and the facts from the cited
  content; that step is open work under issue #163 (HF-103-A).
- The run's trace is not read; the action records are the only account of
  what the run did that the check consults.

Baseline: the grounding check alone. It judges an output, not a claim: an
output it refuses counts as flagging every claim in it, and one it passes
as flagging none.
Layer: the claim check of :func:`check_claims`, which also flags a claim
whose cited anchor the producer did not have.

Metrics:
- planted_detection_rate: planted claims flagged with the planted verdict
  (higher is better)
- false_flag_rate: faithful claims flagged (lower is better)
- unsupported_claim_rate, contradicted_claim_rate: the share of all claims
  the claim check gives each verdict (reported, not gated: the outputs are
  authored, not generated by a model)

The CI gate is :func:`gate`: every planted claim flagged with its verdict,
and no faithful claim flagged.
"""

from __future__ import annotations

import json
import math
from collections.abc import Callable, Iterable, Mapping
from pathlib import Path
from typing import Any

from grounded_agency.grounding import GroundingPolicy, check_output

from .base import BenchmarkScenario

FIXTURES = Path(__file__).resolve().parent.parent / "fixtures" / "explanations"

SUPPORTED = "supported"
UNSUPPORTED = "unsupported"
CONTRADICTED = "contradicted"

_POLICY = GroundingPolicy(require=frozenset({"explain"}), attested=True)


def load_runs(path: Path = FIXTURES / "runs.json") -> list[dict[str, Any]]:
    """The runs and their explain outputs."""
    data: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    runs: list[dict[str, Any]] = data["runs"]
    return runs


def load_planted(path: Path = FIXTURES / "planted.json") -> dict[str, dict[str, str]]:
    """The planted claims: run id -> claim position -> expected verdict."""
    data: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    planted: dict[str, dict[str, str]] = data["planted"]
    return planted


def claims(output: Mapping[str, Any]) -> list[tuple[str, dict[str, Any]]]:
    """The output's premise and chain claims with their positions."""
    found: list[tuple[str, dict[str, Any]]] = []
    for section in ("premises", "chain"):
        for i, claim in enumerate(output.get(section) or []):
            found.append((f"{section}/{i}", claim))
    return found


def _same(a: Any, b: Any) -> bool:
    if isinstance(a, bool) or isinstance(b, bool):
        return a is b
    if isinstance(a, (int, float)) and isinstance(b, (int, float)):
        return math.isclose(a, b, rel_tol=1e-9, abs_tol=1e-12)
    return bool(a == b)


def _values(sources: Iterable[Mapping[str, Any]], subject: str, attribute: str) -> list:
    return [
        fact["value"]
        for source in sources
        for fact in source.get("facts", [])
        if fact.get("subject") == subject and fact.get("attribute") == attribute
    ]


def _holds(left: Any, relation: str, right: Any) -> bool:
    if relation == "<":
        return bool(left < right)
    if relation == ">":
        return bool(left > right)
    raise ValueError(f"unknown relation {relation!r}")


def check_claim(
    claim: Mapping[str, Any], run: Mapping[str, Any], output: Mapping[str, Any]
) -> str:
    """The verdict on one claim.

    A claim may rest only on anchors the output lists in its
    ``evidence_anchors``; an ``acs:<ref>`` anchor names a bound step output
    and any other anchor names an item of the run's ``evidence_seen``.

    - ``contradicted``: a value the cited anchors, the run's evidence or its
      action records state for the claim's subject and attribute differs
      from the claim (for a relation, the known values do not satisfy it).
      The action records are the authoritative account of what was done,
      so they count whether cited or not.
    - ``supported``: not contradicted, and a cited anchor states the value
      (for a relation, cited anchors state both values and they satisfy it).
    - ``unsupported``: neither.
    """
    listed = {a.get("ref") for a in output.get("evidence_anchors") or []}
    cited = [ref for ref in claim.get("cites") or [] if ref in listed]
    evidence = {e["ref"]: e for e in run.get("evidence_seen") or []}
    bound = {b["ref"]: b for b in run.get("bound") or []}
    cited_sources = []
    for ref in cited:
        if ref.startswith("acs:") and ref[4:] in bound:
            cited_sources.append(bound[ref[4:]])
        elif ref in evidence:
            cited_sources.append(evidence[ref])
    every_source = [
        *evidence.values(),
        *bound.values(),
        *(run.get("action_records") or []),
    ]
    subject, attribute = claim["subject"], claim["attribute"]

    if "relation" in claim:
        relation, other = claim["relation"], claim["than"]
        known_left = _values(every_source, subject, attribute)
        known_right = _values(every_source, other, attribute)
        if any(
            not _holds(left, relation, right)
            for left in known_left
            for right in known_right
        ):
            return CONTRADICTED
        cited_left = _values(cited_sources, subject, attribute)
        cited_right = _values(cited_sources, other, attribute)
        if cited_left and cited_right:
            return SUPPORTED
        return UNSUPPORTED

    value = claim["value"]
    if any(not _same(v, value) for v in _values(every_source, subject, attribute)):
        return CONTRADICTED
    if any(_same(v, value) for v in _values(cited_sources, subject, attribute)):
        return SUPPORTED
    return UNSUPPORTED


Checker = Callable[[Mapping[str, Any], Mapping[str, Any], Mapping[str, Any]], str]


def check_claims(
    runs: Iterable[Mapping[str, Any]], checker: Checker = check_claim
) -> dict[str, dict[str, str]]:
    """Every claim's verdict: run id -> claim position -> verdict."""
    return {
        run["id"]: {
            position: checker(claim, run, run["output"])
            for position, claim in claims(run["output"])
        }
        for run in runs
    }


def grounding_verdicts(runs: Iterable[Mapping[str, Any]]) -> dict[str, dict[str, str]]:
    """The grounding check alone, as verdicts: every claim of an output the
    check refuses is ``unsupported``; every claim of one it passes is
    ``supported``. The check sees the anchors, not the claims."""
    verdicts: dict[str, dict[str, str]] = {}
    for run in runs:
        output = run["output"]
        result = check_output(
            output,
            _POLICY,
            bound_refs=[b["ref"] for b in run.get("bound") or []],
            evidence_seen=[e["ref"] for e in run.get("evidence_seen") or []],
        )
        verdict = SUPPORTED if result.ok else UNSUPPORTED
        verdicts[run["id"]] = {position: verdict for position, _ in claims(output)}
    return verdicts


def score(
    verdicts: Mapping[str, Mapping[str, str]],
    planted: Mapping[str, Mapping[str, str]],
) -> dict[str, Any]:
    """Detection, false flags and verdict rates of a set of verdicts."""
    planted_total = planted_caught = planted_flagged = 0
    faithful_total = faithful_flagged = 0
    counts = {SUPPORTED: 0, UNSUPPORTED: 0, CONTRADICTED: 0}
    missed: list[str] = []
    false_flags: list[str] = []
    for run_id, by_position in verdicts.items():
        expected = planted.get(run_id, {})
        for position, verdict in by_position.items():
            counts[verdict] += 1
            where = f"{run_id}:{position}"
            if position in expected:
                planted_total += 1
                if verdict != SUPPORTED:
                    planted_flagged += 1
                if verdict == expected[position]:
                    planted_caught += 1
                else:
                    missed.append(where)
            else:
                faithful_total += 1
                if verdict != SUPPORTED:
                    faithful_flagged += 1
                    false_flags.append(where)
    # Every planted claim must have been checked.
    for run_id, expected in planted.items():
        for position in expected:
            if position not in verdicts.get(run_id, {}):
                planted_total += 1
                missed.append(f"{run_id}:{position}")
    total = sum(counts.values())
    return {
        "planted_detection_rate": planted_caught / planted_total
        if planted_total
        else 0.0,
        "planted_flag_rate": planted_flagged / planted_total if planted_total else 0.0,
        "false_flag_rate": faithful_flagged / faithful_total if faithful_total else 0.0,
        "unsupported_claim_rate": counts[UNSUPPORTED] / total if total else 0.0,
        "contradicted_claim_rate": counts[CONTRADICTED] / total if total else 0.0,
        "claims_checked": total,
        "planted_claims": planted_total,
        "faithful_claims": faithful_total,
        "missed": missed,
        "false_flags": false_flags,
    }


def gate(result: Mapping[str, Any]) -> list[str]:
    """Why a scored result fails the CI gate (empty when it passes): every
    planted claim flagged with its planted verdict, and none of the faithful
    claims flagged. A set with no planted claim or no faithful claim fails,
    since it cannot show that the check can fail."""
    problems = []
    if result["planted_claims"] == 0:
        problems.append("no planted claims: the gate cannot show a miss")
    if result["faithful_claims"] == 0:
        problems.append("no faithful claims: the gate cannot show a false flag")
    if result["missed"]:
        problems.append(f"planted claims missed: {', '.join(result['missed'])}")
    if result["false_flags"]:
        problems.append(f"faithful claims flagged: {', '.join(result['false_flags'])}")
    return problems


class ExplanationFaithfulnessScenario(BenchmarkScenario):
    """Benchmark for claim-level faithfulness of explain outputs."""

    name = "explanation_faithfulness"
    description = (
        "Checks each claim of authored explain outputs against the cited "
        "anchors and the run's records; the grounding check alone is the "
        "baseline"
    )

    def __init__(self, seed: int = 42, verbose: bool = False):
        super().__init__(seed, verbose)
        self.runs: list[dict[str, Any]] = []
        self.planted: dict[str, dict[str, str]] = {}

    def setup(self) -> None:
        self.runs = load_runs()
        self.planted = load_planted()
        self.log(f"Loaded {len(self.runs)} runs")

    def _metrics(self, verdicts: Mapping[str, Mapping[str, str]]) -> dict[str, Any]:
        result = score(verdicts, self.planted)
        return {
            "planted_detection_rate": result["planted_detection_rate"],
            "false_flag_rate": result["false_flag_rate"],
            "unsupported_claim_rate": result["unsupported_claim_rate"],
            "contradicted_claim_rate": result["contradicted_claim_rate"],
            "claims_checked": result["claims_checked"],
            "planted_claims": result["planted_claims"],
            "gate_failures": len(gate(result)),
        }

    def run_baseline(self) -> dict[str, Any]:
        metrics = self._metrics(grounding_verdicts(self.runs))
        self.log(f"Grounding check alone: {metrics}")
        return metrics

    def run_ga(self) -> dict[str, Any]:
        metrics = self._metrics(check_claims(self.runs))
        self.log(f"Claim check: {metrics}")
        return metrics

    def compare(
        self, baseline_result: dict[str, Any], ga_result: dict[str, Any]
    ) -> dict[str, float]:
        return {
            "planted_detection_improvement": ga_result["planted_detection_rate"]
            - baseline_result["planted_detection_rate"],
            "false_flag_change": ga_result["false_flag_rate"]
            - baseline_result["false_flag_rate"],
        }
