"""Generate the files the Standard Agents binding takes from this repository.

The reference binding in examples/standard_agents/ must agree with the
ontology and with the reference executor, so two of its files are generated:

- src/acs/ontology.gen.ts: each capability's layer, safety flags and
  required output fields, and the ontology's `requires` edges, from
  schemas/capability_ontology.yaml
- test/fixtures/approval-digests.json: approval digests (STANDARD v1.1.0
  §5.14) the reference executor computes for a set of shown values, which
  the binding's own digest is tested against

It also writes schemas/interop/standard_agents_annotation.schema.json, the
schema of the annotation the binding puts on a tool, whose capability and
layer lists are the ontology's.

    python scripts/gen_standard_agents_binding.py          # write the files
    python scripts/gen_standard_agents_binding.py --check  # fail if they differ (CI)
"""

import argparse
import json
import sys
import tempfile
from pathlib import Path
from typing import Any

from grounded_agency import _core
from grounded_agency.workflows import Host, WorkflowEngine, WorkflowRunner

ROOT = Path(__file__).resolve().parent.parent
ONTOLOGY = ROOT / "schemas" / "capability_ontology.yaml"
OUT = ROOT / "examples" / "standard_agents"
ANNOTATION_SCHEMA = (
    ROOT / "schemas" / "interop" / "standard_agents_annotation.schema.json"
)
ME = "scripts/gen_standard_agents_binding.py"

HEADER = f"""\
// Generated from schemas/capability_ontology.yaml by
// {ME}. DO NOT EDIT: regenerate with
//   python {ME}
"""


def ts(value: Any) -> str:
    """A JSON literal, which is also a TypeScript literal."""
    return json.dumps(value, ensure_ascii=False)


def render_ontology(ontology: dict[str, Any]) -> str:
    layer_of = {
        capability: layer
        for layer, info in ontology["layers"].items()
        for capability in info["capabilities"]
    }
    lines = [HEADER]
    lines.append(
        f"export const ONTOLOGY_VERSION = {ts(str(ontology['meta']['version']))};"
    )
    lines.append("")
    lines.append("export const CAPABILITIES = {")
    for node in ontology["nodes"]:
        entry = {
            "layer": layer_of[node["id"]],
            "risk": node.get("risk", "low"),
            "mutation": bool(node.get("mutation", False)),
            "requires_checkpoint": bool(node.get("requires_checkpoint", False)),
            "requires_approval": bool(node.get("requires_approval", False)),
            "mutation_overridable": bool(node.get("mutation_overridable", False)),
            "output_required": list(
                (node.get("output_schema") or {}).get("required", [])
            ),
        }
        lines.append(f"  {ts(node['id'])}: {ts(entry)},")
    lines.append("} as const;")
    lines.append("")
    # The only edge type the binding enforces at run time. `precedes` and
    # `conflicts_with` constrain the steps of one workflow, which the
    # workflow validator checks; a thread has no such static list of steps.
    lines.append(
        "/** `requires` edges as [from, to]: `from` must have run before `to`. */"
    )
    lines.append("export const REQUIRES = [")
    lines.extend(
        f"  {ts([e['from'], e['to']])},"
        for e in ontology["edges"]
        if e["type"] == "requires"
    )
    lines.append("] as const;")
    lines.append("")
    return "\n".join(lines)


def render_annotation_schema(ontology: dict[str, Any]) -> str:
    version = {"type": "string", "pattern": r"^\d+\.\d+\.\d+$"}
    schema = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": (
            "https://github.com/synaptiai/agent-capability-standard/"
            "schemas/interop/standard_agents_annotation.schema.json"
        ),
        "title": "Agent Capability Standard annotation for a Standard Agents tool",
        "description": (
            "The value of the `acs` key in a Standard Agent Specification "
            "tool's `annotations`: the ontology capability the tool performs "
            "and its effective safety flags. Generated by "
            f"{ME} from the ontology."
        ),
        "type": "object",
        "required": [
            "standard",
            "ontology",
            "capability",
            "layer",
            "risk",
            "mutation",
            "requires_checkpoint",
            "requires_approval",
        ],
        "additionalProperties": False,
        "properties": {
            "standard": {
                **version,
                "description": (
                    "Version of the Agent Capability Standard the "
                    "classification follows."
                ),
            },
            "ontology": {
                **version,
                "description": (
                    "Version of the capability ontology the capability id "
                    "and flags come from (`meta.version`)."
                ),
            },
            "capability": {
                "enum": [node["id"] for node in ontology["nodes"]],
                "description": "The one ontology capability the tool performs.",
            },
            "layer": {
                "enum": list(ontology["layers"]),
                "description": "The capability's layer.",
            },
            "domain": {
                "type": "string",
                "minLength": 1,
                "description": "The capability's domain parameter, e.g. `config`.",
            },
            "risk": {
                "enum": ["low", "medium", "high"],
                "description": (
                    "Effective risk: the higher of the tool's declaration "
                    "and the ontology's value (Standard §5.2.1)."
                ),
            },
            "mutation": {
                "type": "boolean",
                "description": "Whether the tool changes persistent state.",
            },
            "requires_checkpoint": {
                "type": "boolean",
                "description": "Whether a checkpoint must precede each call.",
            },
            "requires_approval": {
                "type": "boolean",
                "description": "Whether each call needs approval.",
            },
        },
    }
    return json.dumps(schema, indent=2, ensure_ascii=False) + "\n"


# One step that needs approval and shows the value an earlier step returned,
# so the executor computes the digest of whatever the host hands back.
DIGEST_CATALOG = """\
# Standard version: 1.1.0
change:
  goal: Change a setting once a person has approved what will change.
  risk: high
  workflow_extensions:
    requires: [approval@1]
  inputs:
    setting: {type: string, required: true}
  steps:
  - capability: retrieve
    purpose: Read the value to show.
    store_as: current
    input_bindings:
      target: ${setting}
  - capability: checkpoint
    purpose: Save a restore point.
    store_as: cp
    input_bindings:
      scope: config
  - capability: mutate
    purpose: Apply the change.
    store_as: applied
    input_bindings:
      target: ${setting}
      operation: {set: true}
    approval:
      approver: {kind: human}
      shows: ["${current.data}"]
"""

# Values that exercise RFC 8785: member order by UTF-16 code units, number
# forms, string escapes, characters outside the Basic Multilingual Plane.
SHOWN_VALUES: list[Any] = [
    {
        "action": "write_config",
        "capability": "mutate",
        "args": {"key": "a", "value": "b"},
    },
    {"b": 2, "a": 1, "A": 0, "aa": [3, 2, 1], "": None},
    {
        "numbers": [
            0,
            -0.0,
            1,
            -1,
            1.5,
            1e21,
            1e-7,
            123456789012,
            0.1,
            100,
            1.0,
            4.5e-10,
            2**53,
        ]
    },
    {"text": 'line\nbreak\ttab "quote" back\\slash \u0001 \u007f é € \U0001f600'},
    {
        "€": "Euro",
        "\r": "CR",
        "דּ": "Dalet",
        "1": "One",
        "\U0001f600": "Emoji",
        "\u0080": "Control",
        "ö": "o umlaut",
    },
    {"nested": {"z": {"y": {"x": [True, False, None, {"k": []}, {}]}}}},
    "a bare string",
    [1, "two", {"three": 3}],
    42,
    None,
]


class _DigestHost(Host):
    """Returns one value from `retrieve` and keeps the approval action."""

    def __init__(self, value: Any) -> None:
        super().__init__(None)
        self.value = value
        self.approval: dict[str, Any] = {}

    def invoke_capability(self, action: dict[str, Any]) -> dict[str, Any]:
        outputs: dict[str, dict[str, Any]] = {
            "retrieve": {"data": self.value, "confidence": 1.0},
            "checkpoint": {"checkpoint_id": "cp-1"},
            "mutate": {"success": True},
        }
        value = {**outputs[action["capability"]], "evidence_anchors": []}
        return {"kind": "Output", "value": value}

    def request_approval(self, action: dict[str, Any]) -> dict[str, Any]:
        self.approval = action
        return {
            "kind": "Decision",
            "decision_id": "d1",
            "decision": "approved",
            "approvers": ["alice"],
            "digest": action["digest"],
        }


def render_digests() -> str:
    vectors = []
    with tempfile.TemporaryDirectory() as tmp:
        catalog = Path(tmp) / "catalog.yaml"
        catalog.write_text(DIGEST_CATALOG, encoding="utf-8")
        engine = WorkflowEngine(ONTOLOGY, schema_root=ROOT)
        engine.load_catalog(catalog)
        for value in SHOWN_VALUES:
            host = _DigestHost(value)
            result = WorkflowRunner(engine).run(
                "change", {"setting": "x"}, host, run_id="r"
            )
            if not result.ok:
                raise SystemExit(f"the digest workflow failed: {result}")
            vectors.append(
                {"shown": host.approval["shown"], "digest": host.approval["digest"]}
            )
    doc = {
        "generated_by": ME,
        "source": "the reference executor's approval digest (STANDARD v1.1.0 §5.14)",
        "vectors": vectors,
    }
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="fail if the files on disk differ"
    )
    check = parser.parse_args(argv).check
    ontology = _core.load_yaml(str(ONTOLOGY))
    rendered = {
        OUT / "src" / "acs" / "ontology.gen.ts": render_ontology(ontology),
        OUT / "test" / "fixtures" / "approval-digests.json": render_digests(),
        ANNOTATION_SCHEMA: render_annotation_schema(ontology),
    }
    stale = [
        p
        for p, text in rendered.items()
        if not p.exists() or p.read_text(encoding="utf-8") != text
    ]
    if check:
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT)}")
        if stale:
            print(f"run: python {ME}")
            return 1
        print(f"{len(rendered)} Standard Agents binding files up to date")
        return 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(rendered[p], encoding="utf-8")
    print(f"{len(rendered)} files ({len(stale)} written)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
