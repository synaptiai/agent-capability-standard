#!/usr/bin/env python3
"""Sync skill-local files generated from the repository's sources.

- skills/<name>/schemas/output_schema.yaml from each ontology node's
  output_schema
- skills/<name>/reference/workflow_catalog.yaml, for every skill that bundles
  one, regenerated from schemas/workflow_catalog.yaml with its schema paths
  rewritten to co-located copies
- those co-located copies (world_state_schema.yaml, event_schema.yaml,
  transform_mapping_rawlog_to_observation.yaml) next to each bundled catalog,
  and any other copy of them a skill vendors in its reference/ directory

A sync also removes generated output_schema.yaml files the plan no longer
produces (e.g. for a capability removed from the ontology); only files that
carry the generated header are ever removed. --check reports both drift and
such orphans; --dry-run lists the writes and removals without making them.

Usage:
    python tools/sync_skill_schemas.py            # write what changed
    python tools/sync_skill_schemas.py --dry-run  # list what would change
    python tools/sync_skill_schemas.py --check    # exit 1 on drift (CI)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml
from yaml_util import ONTOLOGY_MAX_BYTES, safe_yaml_load

ROOT = Path(__file__).resolve().parents[1]

# Transitive dependencies referenced inside bundled workflow_catalog.yaml.
# Maps repo-root paths → local filenames for both copying and path rewriting.
WORKFLOW_CATALOG_TRANSITIVE_DEPS = {
    "schemas/world_state_schema.yaml": "world_state_schema.yaml",
    "schemas/event_schema.yaml": "event_schema.yaml",
    "schemas/transforms/transform_mapping_rawlog_to_observation.yaml": "transform_mapping_rawlog_to_observation.yaml",
}

# Comment-only references to rewrite with a note
WORKFLOW_CATALOG_COMMENT_REWRITES = {
    "schemas/workflows/": "(repo-level) schemas/workflows/",
}

VENDORED_CATALOG_SOURCE = "schemas/workflow_catalog.yaml"
VENDORED_CATALOG_NOTE = """\
# Vendored copy of schemas/workflow_catalog.yaml, schema paths rewritten to
# the co-located copies. DO NOT EDIT — regenerate with:
# python tools/sync_skill_schemas.py
"""

HEADER_TEMPLATE = """\
# Output schema for the {capability} capability
# Source: schemas/capability_ontology.yaml
# Generated by: tools/sync_skill_schemas.py
# DO NOT EDIT — regenerate with: python tools/sync_skill_schemas.py
"""


def build_layer_index(ontology: dict) -> dict[str, str]:
    """Build a mapping from capability id to layer name."""
    index: dict[str, str] = {}
    for layer_name, layer_info in ontology.get("layers", {}).items():
        for cap_id in layer_info.get("capabilities", []):
            index[cap_id] = layer_name
    return index


def generate_schema_doc(node: dict, layer: str) -> str:
    """Generate the YAML content for a skill's output_schema.yaml."""
    header = HEADER_TEMPLATE.format(capability=node["id"])
    doc = {
        "capability": node["id"],
        "layer": layer,
        "description": node.get("description", ""),
        "output_schema": node.get("output_schema", {}),
    }
    return header + "---\n" + yaml.dump(doc, default_flow_style=False, sort_keys=False)


def rewrite_paths(content: str) -> str:
    """Point a bundled catalog's schema references at the co-located copies.

    Structural references (``ref:``, ``mapping_ref:``, ...) become the local
    file names. Comment-only domain workflow references get one
    ``(repo-level)`` note: every existing prefix is stripped before exactly
    one is re-applied, so the rewrite is idempotent and heals content a past
    run double-prefixed (issue #107).
    """
    for old_path, new_path in WORKFLOW_CATALOG_TRANSITIVE_DEPS.items():
        content = content.replace(old_path, new_path)
    for old_prefix, new_prefix in WORKFLOW_CATALOG_COMMENT_REWRITES.items():
        while new_prefix in content:
            content = content.replace(new_prefix, old_prefix)
        content = content.replace(old_prefix, new_prefix)
    return content


def render_vendored_catalog(source: str) -> str:
    """A skill's copy of the workflow catalog: the source with its paths
    rewritten and a do-not-edit note after the leading comment block's first
    line (which keeps the ``# Standard version:`` header first)."""
    first, newline, rest = source.partition("\n")
    return first + newline + VENDORED_CATALOG_NOTE + rewrite_paths(rest)


def planned_files(root: Path) -> tuple[dict[Path, bytes], list[str]]:
    """Every file the sync owns, with the content it must have.

    - ``skills/<capability>/schemas/output_schema.yaml`` for each ontology
      node that has a skill directory
    - for each skill that bundles ``reference/workflow_catalog.yaml``: that
      catalog regenerated from ``schemas/workflow_catalog.yaml``, and copies
      of the schemas it references

    Returns the plan and the problems found (missing skill directories or
    sources).
    """
    files: dict[Path, bytes] = {}
    errors: list[str] = []
    skills_dir = root / "skills"

    ontology = safe_yaml_load(
        root / "schemas" / "capability_ontology.yaml", max_size=ONTOLOGY_MAX_BYTES
    )
    layer_index = build_layer_index(ontology)
    for node in ontology.get("nodes", []):
        skill_dir = skills_dir / node["id"]
        if not skill_dir.exists():
            errors.append(f"Skill directory missing: skills/{node['id']}/")
            continue
        layer = layer_index.get(node["id"], "UNKNOWN")
        files[skill_dir / "schemas" / "output_schema.yaml"] = generate_schema_doc(
            node, layer
        ).encode("utf-8")

    catalogs = sorted(skills_dir.glob("*/reference/workflow_catalog.yaml"))
    source = root / VENDORED_CATALOG_SOURCE
    if catalogs and not source.exists():
        errors.append(f"Catalog source missing: {VENDORED_CATALOG_SOURCE}")
        return files, errors
    catalog = (
        render_vendored_catalog(source.read_text(encoding="utf-8")).encode("utf-8")
        if catalogs
        else b""
    )
    deps: dict[str, bytes] = {}
    for repo_path, local_name in WORKFLOW_CATALOG_TRANSITIVE_DEPS.items():
        dep = root / repo_path
        if dep.exists():
            deps[local_name] = dep.read_bytes()
        else:
            errors.append(f"Transitive dep missing at repo root: {repo_path}")
    for catalog_path in catalogs:
        files[catalog_path] = catalog
        for local_name, content in deps.items():
            files[catalog_path.parent / local_name] = content
    # A skill may vendor a schema without bundling a catalog (e.g.
    # skills/receive/reference/event_schema.yaml); keep those copies current
    # too, so no copy of a source schema is left unmaintained (#107).
    for local_name, content in deps.items():
        for copy in sorted(skills_dir.glob(f"*/reference/{local_name}")):
            files.setdefault(copy, content)
    return files, errors


def _same_text(a: bytes, b: bytes) -> bool:
    """Equal up to line endings, so a CRLF checkout is not drift."""
    return a.replace(b"\r\n", b"\n") == b.replace(b"\r\n", b"\n")


def drifted(files: dict[Path, bytes]) -> list[Path]:
    """The planned files whose content on disk differs (or that are missing)."""
    return [
        path
        for path, content in files.items()
        if not path.is_file() or not _same_text(path.read_bytes(), content)
    ]


def orphans(root: Path, files: dict[Path, bytes]) -> list[Path]:
    """Generated output schemas the plan no longer produces, e.g. for a
    capability removed from the ontology. Only files carrying the generated
    header count, so nothing written by hand is ever reported or removed."""
    marker = b"# Generated by: tools/sync_skill_schemas.py"
    return [
        path
        for path in sorted((root / "skills").glob("*/schemas/output_schema.yaml"))
        if path not in files and marker in path.read_bytes()
    ]


def main() -> None:
    ap = argparse.ArgumentParser(
        description="Sync skill-local schemas and bundled workflow catalogs "
        "from the repository sources"
    )
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument(
        "--dry-run",
        action="store_true",
        help="List the files a sync would change without writing them",
    )
    mode.add_argument(
        "--check",
        action="store_true",
        help="Exit 1 if any generated file has drifted from its source",
    )
    ap.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)
    args = ap.parse_args()
    root = args.root.resolve()

    if not (root / "schemas" / "capability_ontology.yaml").exists():
        print(f"ERROR: Ontology not found under {root}")
        sys.exit(1)

    files, errors = planned_files(root)
    if errors:
        print("PROBLEMS:")
        for e in errors:
            print(f"  - {e}")

    stale = drifted(files)
    unowned = orphans(root, files)
    if args.check:
        if stale or unowned:
            print(
                f"DRIFT: {len(stale)} generated file(s) differ from their source, "
                f"{len(unowned)} no longer generated:"
            )
            for path in [*stale, *unowned]:
                print(f"  - {path.relative_to(root)}")
            print("Run: python tools/sync_skill_schemas.py")
            sys.exit(1)
        if errors:
            print("SYNC CHECK FAIL: see the problems above")
            sys.exit(1)
        print(f"SYNC CHECK PASS: {len(files)} generated files up to date")
        sys.exit(0)

    for path in stale:
        if args.dry_run:
            print(f"  [dry-run] Would write: {path.relative_to(root)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(files[path])
    for path in unowned:
        if args.dry_run:
            print(f"  [dry-run] Would remove: {path.relative_to(root)}")
        else:
            path.unlink()
    prefix = "[dry-run] " if args.dry_run else ""
    print(
        f"{prefix}SYNC COMPLETE: {len(stale)} of {len(files)} generated files "
        f"changed, {len(unowned)} removed"
    )
    if errors:
        sys.exit(1)


if __name__ == "__main__":
    main()
